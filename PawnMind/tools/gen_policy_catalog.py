#!/usr/bin/env python3
"""Generate src/Core/PolicyCatalog.g.cs from the canonical Python policy.

The same JSON that drives ``tool_policy.py`` drives the C# runtime gate, so the
two sides cannot drift into different allowlists. The generated file is checked
in (the Unity build has no Python) and a unit test fails when it is stale.

Usage:
    python3 tools/gen_policy_catalog.py          # write the file
    python3 tools/gen_policy_catalog.py --check  # exit 1 when stale
"""

import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MOD_DIR = os.path.dirname(HERE)
AGENT_DIR = os.path.join(MOD_DIR, "agent")
OUTPUT = os.path.join(MOD_DIR, "src", "Core", "PolicyCatalog.g.cs")

sys.path.insert(0, AGENT_DIR)
import tool_policy  # noqa: E402


def canonical_sha256(policy):
    # One hash implementation, shared with the MCP client's compatibility guard.
    return tool_policy.policy_sha256(policy)


def _array(values):
    items = ", ".join('"%s"' % value for value in sorted(values))
    return "{ " + items + " }"


def render(policy):
    schema = str(policy.get("schema", ""))
    sha = canonical_sha256(policy)
    bootstrap = sorted(tool_policy.allowlist(policy, "bootstrap"))
    play = sorted(tool_policy.play_allowlist(policy))
    readers = sorted(tool_policy.SNAPSHOT_READERS)

    lines = [
        "// <auto-generated>",
        "// Generated by tools/gen_policy_catalog.py from agent/policy/tool_policy.json.",
        "// Do not edit by hand: change the JSON, rerun the generator, commit both.",
        "// </auto-generated>",
        "namespace PawnMind.Core",
        "{",
        "    /// <summary>Runtime mirror of the Python tool policy.</summary>",
        "    public static class PolicyCatalog",
        "    {",
        '        public const string Schema = "%s";' % schema,
        '        public const string Sha256 = "%s";' % sha,
        "",
        "        /// <summary>Tools that read the state snapshot; never allowed in Bootstrap.</summary>",
        "        public static readonly string[] SnapshotReaders = %s;" % _array(readers),
        "",
        "        /// <summary>Bootstrap (main menu) operations.</summary>",
        "        public static readonly string[] BootstrapOps = %s;" % _array(bootstrap),
        "",
        "        /// <summary>",
        "        /// Play operations: only tools with reviewed live evidence. Empty until a",
        "        /// real game session records that evidence, so Play stays closed by design.",
        "        /// </summary>",
        "        public static readonly string[] PlayOps = %s;" % _array(play),
        "",
        "        public static bool IsSnapshotReader(string op)",
        "        {",
        "            if (string.IsNullOrEmpty(op)) return false;",
        "            for (int i = 0; i < SnapshotReaders.Length; i++)",
        "            {",
        "                if (SnapshotReaders[i] == op) return true;",
        "            }",
        "            return false;",
        "        }",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    policy = tool_policy.load_policy()
    text = render(policy)
    check = "--check" in argv

    if check:
        try:
            with open(OUTPUT, encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            print("stale: %s is missing" % OUTPUT, file=sys.stderr)
            return 1
        if current != text:
            print("stale: %s does not match tool_policy.json; rerun the generator"
                  % OUTPUT, file=sys.stderr)
            return 1
        print("ok: %s matches tool_policy.json (sha256 %s)"
              % (OUTPUT, canonical_sha256(policy)))
        return 0

    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("wrote %s (sha256 %s)" % (OUTPUT, canonical_sha256(policy)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
