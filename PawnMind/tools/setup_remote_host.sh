#!/usr/bin/env bash
# Prepare a Linux build host for the PawnMind offline test suites.
#
# The repository itself is copied separately (see
# docs/plans/SERVER_MIGRATION_2026-11-17.md). This script only installs the two
# toolchains the suites need, and verifies them. It never touches the game, the
# saves, or the Mod install directory.
#
# Usage (as root):
#   ./tools/setup_remote_host.sh
#
# Environment:
#   DOTNET_ROOT_DIR  install directory for the SDK (default /root/.dotnet)
#   DOTNET_CHANNEL   SDK channel (default 9.0; the test projects target net9.0)
#   PYTHON_BIN       interpreter used to create .venv (default python3)
#   MANAGED_DIR      directory holding the game's Managed DLLs (for adapter tests)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DOTNET_ROOT_DIR="${DOTNET_ROOT_DIR:-/root/.dotnet}"
DOTNET_CHANNEL="${DOTNET_CHANNEL:-9.0}"
PYTHON_BIN="${PYTHON_BIN:-python3}"
MANAGED_DIR="${MANAGED_DIR:-/root/work/game_managed}"

say() { printf '[setup] %s\n' "$*"; }

# 1. .NET SDK -----------------------------------------------------------------
if [ -x "$DOTNET_ROOT_DIR/dotnet" ]; then
  say "dotnet already present: $("$DOTNET_ROOT_DIR/dotnet" --version)"
else
  say "installing .NET SDK channel $DOTNET_CHANNEL into $DOTNET_ROOT_DIR"
  curl -fsSL https://dot.net/v1/dotnet-install.sh -o /tmp/dotnet-install.sh
  bash /tmp/dotnet-install.sh --channel "$DOTNET_CHANNEL" --install-dir "$DOTNET_ROOT_DIR" --no-path
fi
export DOTNET_ROOT="$DOTNET_ROOT_DIR"
export PATH="$DOTNET_ROOT_DIR:$PATH"
command -v dotnet >/dev/null || ln -sf "$DOTNET_ROOT_DIR/dotnet" /usr/local/bin/dotnet
say "dotnet: $(dotnet --version)"
say "sdks: $(dotnet --list-sdks | tr '\n' ' ')"

# 2. Python venv --------------------------------------------------------------
cd "$ROOT"
if [ ! -x .venv/bin/python ]; then
  say "creating .venv with $PYTHON_BIN"
  "$PYTHON_BIN" -m venv .venv
fi
.venv/bin/pip -q install --upgrade pip
# The MCP server imports only the MCP SDK; tests use the standard library.
.venv/bin/pip -q install "mcp==2.3.0" pydantic
say "python: $(.venv/bin/python -V) / mcp $(.venv/bin/python -c 'import mcp;print(getattr(mcp,"__version__","?"))')"

# 3. Environment file ---------------------------------------------------------
cat > "$ROOT/.env.server" <<EOF
# Generated by tools/setup_remote_host.sh — host-local paths, do not commit.
export DOTNET="$DOTNET_ROOT_DIR/dotnet"
export GAME_MANAGED="$MANAGED_DIR"
export PAWNMIND_NEWTONSOFT_DLL="$MANAGED_DIR/Newtonsoft.Json.dll"
EOF
say "wrote .env.server"

# 4. Smoke check --------------------------------------------------------------
say "running the Python suite"
.venv/bin/python -B -m unittest discover -s agent/tests

say "running the C# suites (contract checks need $MANAGED_DIR/Assembly-CSharp.dll)"
if [ -f "$MANAGED_DIR/Assembly-CSharp.dll" ]; then
  set -a; . "$ROOT/.env.server"; set +a
  ./test.sh
else
  say "SKIP C# suites: missing $MANAGED_DIR/Assembly-CSharp.dll"
fi

say "done"
